export const getQuestionBank = (): Question[] => {
  try {
    const custom = localStorage.getItem('bcs_custom_questions');
    if (custom) {
      const parsed: Question[] = JSON.parse(custom);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Merge without duplicates by id
        const map = new Map<string, Question>();
        INITIAL_QUESTION_BANK.forEach(q => map.set(q.id, q));
        parsed.forEach(q => map.set(q.id, q));
        return Array.from(map.values());
      }
    }
  } catch (e) {
    console.error('Failed to load custom questions from storage:', e);
  }
  return INITIAL_QUESTION_BANK;
};

export const saveQuestionsToBank = (newQuestions: Question[]) => {
  try {
    const existing = getQuestionBank();
    const map = new Map<string, Question>();
    existing.forEach(q => map.set(q.id, q));
    newQuestions.forEach(q => map.set(q.id, q));
    const merged = Array.from(map.values());
    localStorage.setItem('bcs_custom_questions', JSON.stringify(merged));
  } catch (e) {
    console.error('Failed to save questions to bank:', e);
  }
};
